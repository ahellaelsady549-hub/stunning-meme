const DICTS: Record<Lang, Dict> = { ar: AR, en: EN };

export const CATEGORY_KEYS = ["الكل", "رجالي", "حريمي", "أحذية", "إكسسوارات"] as const;
export function categoryLabel(cat: string, lang: Lang) {
  const map: Record<string, keyof typeof AR> = {
    "الكل": "all",
    "رجالي": "men",
    "حريمي": "women",
    "أحذية": "shoes",
    "إكسسوارات": "accessories",
  };
  const key = map[cat];
  return key ? DICTS[lang][key] : cat;
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: keyof typeof AR) => string; dir: "rtl" | "ltr" };
const I18nContext = createContext<Ctx | null>(null);
const LS = "app_lang_v1";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(LS) as Lang | null;
      if (saved === "ar" || saved === "en") setLangState(saved);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(LS, l); } catch {}
  };

  const t = (k: keyof typeof AR) => DICTS[lang][k] ?? String(k);
  const dir = lang === "ar" ? "rtl" : "ltr";

  return <I18nContext.Provider value={{ lang, setLang, t, dir }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function formatMoney(n: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "ar" ? "ar-EG" : "en-EG", {
    style: "currency",
    currency: "EGP",
    maximumFractionDigits: 0,
  }).format(n);
}

